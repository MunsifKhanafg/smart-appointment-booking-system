// Time Slots Generator
export const generateTimeSlots = () => {
  const slots = [];
  const startHour = 9;
  const endHour = 18;
  
  for (let hour = startHour; hour < endHour; hour++) {
    slots.push(`${hour.toString().padStart(2, '0')}:00`);
    slots.push(`${hour.toString().padStart(2, '0')}:30`);
  }
  
  return slots;
};

// Storage Keys
export const STORAGE_KEYS = {
  BOOKINGS: 'healthcarePlus_bookings',
  BOOKING_COUNTER: 'healthcarePlus_bookingCounter'
};

// Booking Status
export const BOOKING_STATUS = {
  PENDING: 'pending',
  APPROVED: 'approved',
  CANCELLED: 'cancelled'
};

// Get all bookings from localStorage
export const getBookings = () => {
  try {
    const bookings = localStorage.getItem(STORAGE_KEYS.BOOKINGS);
    return bookings ? JSON.parse(bookings) : [];
  } catch (error) {
    console.error('Error reading bookings:', error);
    return [];
  }
};

// Save bookings to localStorage
export const saveBookings = (bookings) => {
  try {
    localStorage.setItem(STORAGE_KEYS.BOOKINGS, JSON.stringify(bookings));
    return true;
  } catch (error) {
    console.error('Error saving bookings:', error);
    return false;
  }
};

// Get next booking ID
export const getNextBookingId = () => {
  try {
    const counter = localStorage.getItem(STORAGE_KEYS.BOOKING_COUNTER);
    const nextId = counter ? parseInt(counter) + 1 : 1;
    localStorage.setItem(STORAGE_KEYS.BOOKING_COUNTER, nextId.toString());
    return `BKG${nextId.toString().padStart(5, '0')}`;
  } catch (error) {
    console.error('Error generating booking ID:', error);
    return `BKG${Date.now()}`;
  }
};

// Check if slot is available
export const isSlotAvailable = (serviceId, date, timeSlot) => {
  const bookings = getBookings();
  return !bookings.some(
    booking => 
      booking.serviceId === serviceId &&
      booking.date === date &&
      booking.timeSlot === timeSlot &&
      booking.status !== BOOKING_STATUS.CANCELLED
  );
};

// Add new booking
export const addBooking = (bookingData) => {
  try {
    const bookings = getBookings();
    const newBooking = {
      ...bookingData,
      id: getNextBookingId(),
      status: BOOKING_STATUS.PENDING,
      createdAt: new Date().toISOString()
    };
    bookings.push(newBooking);
    saveBookings(bookings);
    return newBooking;
  } catch (error) {
    console.error('Error adding booking:', error);
    return null;
  }
};

// Update booking status
export const updateBookingStatus = (bookingId, newStatus) => {
  try {
    const bookings = getBookings();
    const bookingIndex = bookings.findIndex(b => b.id === bookingId);
    
    if (bookingIndex !== -1) {
      bookings[bookingIndex].status = newStatus;
      bookings[bookingIndex].updatedAt = new Date().toISOString();
      saveBookings(bookings);
      return true;
    }
    return false;
  } catch (error) {
    console.error('Error updating booking status:', error);
    return false;
  }
};

// Format date for display
export const formatDate = (dateString) => {
  const date = new Date(dateString);
  const options = { year: 'numeric', month: 'long', day: 'numeric' };
  return date.toLocaleDateString('en-US', options);
};

// Get minimum bookable date (today)
export const getMinDate = () => {
  const today = new Date();
  return today.toISOString().split('T')[0];
};

// Get maximum bookable date (30 days from now)
export const getMaxDate = () => {
  const maxDate = new Date();
  maxDate.setDate(maxDate.getDate() + 30);
  return maxDate.toISOString().split('T')[0];
};

// Get service by ID
export const getServiceById = (serviceId) => {
  return medicalServices.find(service => service.id === parseInt(serviceId));
};
